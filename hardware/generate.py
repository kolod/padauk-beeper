class Pin:
    """A symbol pin given by its connection (wire) point and the side it sticks out of."""

    def __init__(self, number, name, x, y, side, length, etype="Passive", show_name=False):
        self.number, self.name, self.x, self.y, self.side, self.length = number, name, x, y, side, length
        self.etype, self.show_name = etype, show_name

    def body_end(self):
        _, (dx, dy) = PIN_OUTWARD[self.side]
        return self.x - dx * self.length, self.y - dy * self.length


class Symbol:
    def __init__(self, name, refdes, value, pins, shapes, pattern=None, port=False, standard=None):
        self.name, self.refdes, self.value, self.pattern, self.port = name, refdes, value, pattern, port
        # standard: (library file, width, height) of a symbol copied from a DipTrace standard
        # library; its geometry is kept exactly as DipTrace has it.
        self.standard = standard
        if standard:
            self.pins, self.shapes = pins, shapes
            self.width, self.height = standard[1], standard[2]
            return
        # Re-centre on the bounding box of pins and shapes, like DipTrace does.
        xs, ys = [], []
        for p in pins:
            bx, by = p.body_end()
            xs += [p.x, bx]
            ys += [p.y, by]
        for typ, pts, *_ in shapes:
            if typ != "Text":
                xs += [q[0] for q in pts]
                ys += [q[1] for q in pts]
        cx, cy = (min(xs) + max(xs)) / 2, (min(ys) + max(ys)) / 2
        self.width, self.height = max(xs) - min(xs), max(ys) - min(ys)
        for p in pins:
            p.x, p.y = p.x - cx, p.y - cy
        self.pins = pins
        self.shapes = [(typ, [(q[0] - cx, q[1] - cy) for q in pts], *rest) for typ, pts, *rest in shapes]

    def pin_index(self, number):
        return next(i for i, p in enumerate(self.pins) if p.number == number)

    def connection(self, index):
        """Connection point of a pin, relative to the symbol center."""
        p = self.pins[index]
        return p.x, p.y

    def xml(self, parent, index, pattern_keys):
        comp = sub(parent, "Component", Id=index, ComponentStyle=f"CompType{index}")
        part = sub(comp, "Part", Id=0, RefDes=self.refdes, PartType="Net Port" if self.port else "Normal",
                   ShowNumbers="Hide" if self.port else "Common", Type="Free", Int1=0, Int2=0,
                   Width=float(self.width), Height=float(self.height),
                   LockTypeChange="Y" if self.standard else "N", SubFolderIndex=0)
        if self.pattern:
            sub(part, "Pattern", Style=f"PatType{pattern_keys.index(self.pattern)}")
        sub(part, "Name", self.name)
        sub(part, "PartName", "Part 1")
        if self.standard:
            lp = sub(part, "LibPath")
            sub(lp, "Path", rf"C:\Program Files\DipTrace\Lib\{self.standard[0]}")
            sub(lp, "Var", rf"%standardlibs%\{self.standard[0]}")
        else:
            sub(part, "Value", self.value)
        sub(part, "Origin", X=0, Y=0)
        pins = sub(part, "Pins")
        pattern = PATTERNS[self.pattern] if self.pattern else None
        for i, p in enumerate(self.pins):
            orient, _ = PIN_OUTWARD[p.side]
            bx, by = p.body_end()
            pad_id = pattern.pad_ids(p.number)[0] if pattern else -1
            el = sub(pins, "Pin", Id=i, X=float(bx), Y=float(by), Locked="N", Type="Default",
                     ElectricType=p.etype, Orientation=orient, PadId=pad_id, Length=float(p.length),
                     ShowName="Y" if p.show_name else "N")
            sub(el, "Name", p.name)
            sub(el, "PadNumber", p.number)
        shapes = sub(part, "Shapes")
        for i, (typ, pts, *text) in enumerate(self.shapes):
            attrs = dict(Id=i, Type=typ, Locked="N")
            if typ == "Text":
                attrs.update(FontVector="Y", FontSize=5, FontWidth=-2, FontScale=1,
                             TextShow="Name" if text[0] is None else "Any Text",
                             HorzAlign="Center", VertAlign="Center", TextAlign="Center", Angle=0)
            else:
                attrs["LineWidth"] = 0.25
            s = sub(shapes, "Shape", **attrs)
            if text and text[0] is not None:
                lines = sub(s, "TextLines")
                sub(lines, "TextLine", text[0])
            points(s, pts)


