    wires = {n: [] for n in NETS}
    ports = []

    def port(symbol, net, x, y):
        """Place a port so that its connection point lands on (x, y)."""
        cx, cy = SYMBOLS[symbol].connection(0)
        ports.append((symbol, net, x - cx, y - cy))
        return ("port", len(ports) - 1)

    def wire(net, a, b, pts, hidden=False):
        wires[net].append({"ends": (a, b), "pts": pts, "hidden": hidden})

    for net, up in (("VDD", 1), ("GND", -1)):
        for ref, num in NETS[net]:
            x, y = pin_abs(ref, num)
            dx, dy = pin_outward(ref, num)
            if dy == up:                      # pin already points toward the port
                pts = [(x, y), (x, y + up * G)]
            else:                             # side pin: out, then past the symbol's edge
                sym = SYMBOLS[PARTS[ref][0]]
                edge = PARTS[ref][2][1] + up * sym.height / 2
                ty = max(y + G, edge + G) if up > 0 else min(y - G, edge - G)
                pts = [(x, y), (x + dx * 2 * G, y), (x + dx * 2 * G, ty)]
            wire(net, ("pin", ref, num), port(net, net, *pts[-1]), pts)

    for net, members in NETS.items():
        if net in ("VDD", "GND"):
            continue
        for a, b in zip(members, members[1:]):
            wire(net, ("pin", *a), ("pin", *b), [pin_abs(*a), pin_abs(*b)], hidden=net not in VISIBLE_NETS)

    return wires, ports


