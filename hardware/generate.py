# --------------------------------------------------------------------------------------
# Symbol pin convention, as DipTrace saves it:
# - <Pin X Y> is the end of the pin at the symbol body; the wire connects Length away.
# - Orientation is the direction the pin sticks out of the body.
# - DipTrace re-centres every symbol on its bounding box (pins included), so symbols are
#   re-centred here too and the schematic wires match what DipTrace shows.
PIN_OUTWARD = {"L": ("0", (-1, 0)), "R": ("180", (1, 0)), "T": ("90", (0, 1)), "B": ("270", (0, -1))}


def fmt(v):
    """Real number with a dot, no trailing zeros."""
    s = f"{v:.4f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def sub(parent, tag, text=None, **attrs):
    el = ET.SubElement(parent, tag, {k: (fmt(v) if isinstance(v, float) else str(v)) for k, v in attrs.items()})
    if text is not None:
        el.text = str(text)
    return el


def points(parent, pts, **extra):
    ps = sub(parent, "Points")
    for x, y in pts:
        sub(ps, "Point", X=float(x), Y=float(y), **extra)
    return ps


