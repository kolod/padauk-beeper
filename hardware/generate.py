def check():
    """Sanity checks: every net member exists, nothing on the board overlaps the edge."""
    for name, members in NETS.items():
        for ref, num in members:
            sym = SYMBOLS[PARTS[ref][0]]
            sym.pin_index(num)
            assert PATTERNS[sym.pattern].pad_ids(num), (ref, num)
    hw, hh = BOARD_W / 2, BOARD_H / 2
    for ref, (skey, _, _, (x, y, ang, side)) in PARTS.items():
        pat = PATTERNS[SYMBOLS[skey].pattern]
        for _, key, px, py in pat.pads:
            st = PAD_STYLES[key]
            assert abs(x + px) + st.w / 2 <= hw - 0.3 and abs(y + py) + st.h / 2 <= hh - 0.3, (ref, px, py)


if __name__ == "__main__":
    check()
    library()
    if "--schematic" in sys.argv:
        schematic()
    if "--pcb" in sys.argv:
        pcb()
