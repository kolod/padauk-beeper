def rotate(x, y, deg):
    a = math.radians(deg)
    return x * math.cos(a) - y * math.sin(a), x * math.sin(a) + y * math.cos(a)


def pin_abs(refdes, number):
    sym = SYMBOLS[PARTS[refdes][0]]
    px, py, ang = PARTS[refdes][2]
    x, y = rotate(*sym.connection(sym.pin_index(number)), ang)
    return round(px + x, 4), round(py + y, 4)


def pin_outward(refdes, number):
    """Direction a pin sticks out of its symbol, after the part's rotation."""
    sym = SYMBOLS[PARTS[refdes][0]]
    _, (dx, dy) = PIN_OUTWARD[sym.pins[sym.pin_index(number)].side]
    x, y = rotate(dx, dy, PARTS[refdes][2][2])
    return round(x), round(y)


