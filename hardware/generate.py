class PadStyle:
    def __init__(self, name, w, h, shape="Rectangle", corner=0, hole=None, paste=True):
        self.name, self.w, self.h, self.shape, self.corner, self.hole, self.paste = (
            name, w, h, shape, corner, hole, paste)

    def xml(self, parent):
        attrs = {"Name": self.name, "Type": "Through" if self.hole else "Surface"}
        if self.hole:
            attrs.update(HoleType="Round", Hole=float(self.hole))
        ps = sub(parent, "PadStyle", **attrs)
        ms = {"Shape": self.shape, "Width": float(self.w), "Height": float(self.h), "XOff": 0, "YOff": 0}
        if self.corner:
            ms["Corner"] = self.corner
        sub(ps, "MainStack", **ms)
        if not self.paste:
            sub(ps, "MaskPaste", TopMask="Open", BotMask="Open", TopPaste="No Solder", BotPaste="No Solder")


