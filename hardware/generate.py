def write(root, filename):
    ET.indent(root, space=" ")
    data = ET.tostring(root, encoding="unicode")
    (OUT / filename).write_text('<?xml version="1.0" encoding="UTF-8"?>\n' + data + "\n", encoding="utf-8")
    print("wrote", filename)


def schematic():
    wires, ports = build_schematic_wires()
    root = ET.Element("Source", Type="DipTrace-Schematic", Version=VERSION, Units="mm")
    component_library(root, SYMBOL_KEYS, PATTERN_KEYS)
    sch = sub(root, "Schematic")

    ss = sub(sch, "SheetSettings")
    sub(ss, "DisplayTitles", "N")
    sub(ss, "DisplaySheet", "Y")
    sub(ss, "ActiveSheet", 0)
    sheets = sub(ss, "Sheets")
    sh = sub(sheets, "Sheet")
    for tag, val in [("Id", 0), ("Name", "Beeper"), ("Type", "Normal"), ("BlockId", 0), ("XPos", 0),
                     ("YPos", 0), ("Scale", 100), ("SheetWidth", 297), ("SheetHeight", 210),
                     ("LeftMargin", 5), ("TopMargin", 5), ("RightMargin", 5), ("BottomMargin", 5)]:
        sub(sh, tag, val)

    sub(sch, "DesignCache", Count=len(SYMBOL_KEYS))
    nc = sub(sch, "NetClasses")
    c = sub(nc, "NetClass", Id=0, UpdateId=0, Type="Normal")
    sub(c, "Name", "Default")

    net_of = {}
    for n, members in NETS.items():
        for m in members:
            net_of[m] = NET_NAMES.index(n)
    comps = sub(sch, "Components")
    pid = 0
    for ref, (skey, value, (x, y, ang), _) in PARTS.items():
        sym = SYMBOLS[skey]
        SCH_PART_IDS[ref] = pid
        p = sub(comps, "Part", Id=pid, UpdateId=pid, ComponentStyle=f"CompType{SYMBOL_KEYS.index(skey)}",
                ComponentPart=0, Sheet=0, X=float(x), Y=float(y), Angle=float(math.radians(ang)),
                HorzFlip="N", VertFlip="N", ShowNumbers="Common", Group=-1, Selected="N", Locked="N")
        sub(p, "RefDes", ref)
        sub(p, "PartName", "Part 1")
        sub(p, "Value", value)
        sub(p, "Name", sym.name)
        pins = sub(p, "Pins")
        for pin_ in sym.pins:
            nid = net_of.get((ref, pin_.number), -1)
            nc_ = "Y" if (ref, pin_.number) in NOT_CONNECTED else "N"
            sub(pins, "Pin", NetId=nid, NotConnected=nc_)
        pid += 1
    port_ids = []
    for i, (skey, net, x, y) in enumerate(ports):
        port_ids.append(pid)
        p = sub(comps, "Part", Id=pid, UpdateId=pid, ComponentStyle=f"CompType{SYMBOL_KEYS.index(skey)}",
                ComponentPart=0, Sheet=0, X=float(x), Y=float(y), Angle=0, HorzFlip="N", VertFlip="N",
                ShowNumbers="Hide", Group=-1, Selected="N", Locked="N")
        sub(p, "RefDes", f"NetPort{i + 1}")
        sub(p, "PartName", "Part 1")
        sub(p, "Value", "")
        sub(p, "Name", net)
        pins = sub(p, "Pins")
        sub(pins, "Pin", NetId=NET_NAMES.index(net), NotConnected="N")
        pid += 1

    nets = sub(sch, "Nets")
    for nid, name in enumerate(NET_NAMES):
        n = sub(nets, "Net", Id=nid, NetClass=0, UniteByName="N", ConnectPinByName="N", Global="N",
                CustomColor="N", WireColor=0, Locked="N", Enabled="Y")
        sub(n, "Name", name)
        items = sub(n, "Pins")
        for ref, num in NETS[name]:
            sym = SYMBOLS[PARTS[ref][0]]
            sub(items, "Item", Part=SCH_PART_IDS[ref], Pin=sym.pin_index(num))
        for i, (_, pnet, _, _) in enumerate(ports):
            if pnet == name:
                sub(items, "Item", Part=port_ids[i], Pin=0)
        ws = sub(n, "Wires")
        for wid, w in enumerate(wires[name]):
            attrs = dict(Id=wid, Sheet=-1 if w["hidden"] else 0)
            for k, end in zip((1, 2), w["ends"]):
                if end[0] == "pin":
                    ref, num = end[1], end[2]
                    attrs.update({f"Connected{k}": "Pin", f"Bus{k}": -1, f"Object{k}": SCH_PART_IDS[ref],
                                  f"SubObject{k}": SYMBOLS[PARTS[ref][0]].pin_index(num)})
                elif end[0] == "port":
                    attrs.update({f"Connected{k}": "Pin", f"Bus{k}": -1, f"Object{k}": port_ids[end[1]],
                                  f"SubObject{k}": 0})
                else:
                    attrs.update({f"Connected{k}": "Wire", f"Bus{k}": -1, f"Object{k}": end[1],
                                  f"SubObject{k}": end[2]})
            attrs.update(HiddenPower="N", CanUnhide="Y" if w["hidden"] else "N", Arrows="None", Group=-1,
                         Selected="N")
            we = sub(ws, "Wire", **attrs)
            ps = sub(we, "Points")
            prev = None
            for x, y in w["pts"]:
                d = -1 if prev is None else (0 if abs(prev[1] - y) < 1e-6 else 1)
                sub(ps, "Point", X=float(x), Y=float(y), Dir=d)
                prev = (x, y)
    write(root, "beeper.dchxml")


