def pcb():
    physical = [k for k in SYMBOL_KEYS if not SYMBOLS[k].port]
    root = ET.Element("Source", Type="DipTrace-PCB", Version=VERSION, Units="mm")
    component_library(root, physical, PATTERN_KEYS)
    board = sub(root, "Board")

    bo = sub(board, "BoardOutline", Locked="N", Selected="N")
    hw, hh = BOARD_W / 2, BOARD_H / 2
    points(bo, [(-hw, -hh), (hw, -hh), (hw, hh), (-hw, hh)])

    layers = sub(board, "CopperLayers")
    for i, (name, color) in enumerate([("Top", 4227327), ("Bottom", 16744448)]):
        lay = sub(layers, "Lay", Id=i, Type="Signal", PlanePad="By Pads", NetId=-1, PlaneRing=0.2,
                  Color=color, Locked="N")
        sub(lay, "Name", name)

    vias = sub(board, "ViaStyles")
    v = sub(vias, "ViaStyle", Id=0, Size=0.6, HoleSize=0.3, Lay1=0, Lay2=1)
    sub(v, "Name", "Default")

    ncs = sub(board, "NetClasses")
    nc = sub(ncs, "NetClass", Id=0, UpdateId=0, Type="Normal", AllLayers="Y", CheckLength="N", AllVias="Y",
             PerformDRC="N")
    sub(nc, "Name", "Default")
    lps = sub(nc, "LayProperties")
    for name in ("Top", "Bottom"):
        lp = sub(lps, "LayProperty", Width=0.3, MinWidth=0.2, MaxWidth=5, Clearance=0.2)
        sub(lp, "LayerName", name)
    av = sub(nc, "AllowedVias")
    sub(av, "ViaStyle", 0)

    net_of = {}
    for n, members in NETS.items():
        for m in members:
            net_of[m] = NET_NAMES.index(n)
    comps = sub(board, "Components")
    comp_ids = {}
    for cid, (ref, (skey, value, _, (x, y, ang, side))) in enumerate(PARTS.items()):
        sym = SYMBOLS[skey]
        pat = PATTERNS[sym.pattern]
        comp_ids[ref] = cid
        c = sub(comps, "Component", Id=cid, UpdateId=list(PARTS).index(ref),
                PatternStyle=f"PatType{PATTERN_KEYS.index(sym.pattern)}", X=float(x), Y=float(y),
                Angle=float(math.radians(ang)), Side=side, Flip="N", HorzFlip="N", Group=-1,
                Locked="N", Selected="N")
        sub(c, "RefDes", ref)
        sub(c, "Name", sym.name)
        sub(c, "Value", value)
        pads = sub(c, "Pads")
        for i, (number, _, _, _) in enumerate(pat.pads):
            sub(pads, "Pad", Id=pat.pad_id(i), NetId=net_of.get((ref, number), -1), InternalConnection=-1)

    nets = sub(board, "Nets")
    for nid, name in enumerate(NET_NAMES):
        n = sub(nets, "Net", Id=nid, NetClass=0, Locked="N")
        sub(n, "Name", name)
        items = sub(n, "Pads")
        for ref, num in NETS[name]:
            pat = PATTERNS[SYMBOLS[PARTS[ref][0]].pattern]
            for pad in pat.pad_ids(num):
                sub(items, "Item", Comp=comp_ids[ref], Pad=pad)

    shapes = sub(board, "Shapes")
    labels = [("S0", -10.0, -7.6), ("S1", -6.0, -7.6), ("S2", -2.2, -7.6), ("1", -8.6, 10.8),
              ("BEEPER", 6.2, 8.3)]
    for i, (text, x, y) in enumerate(labels):
        s = sub(shapes, "Shape", Id=i, Type="Text", AllLayers="N", Layer="Top Silk", LayId=-1, Angle=0,
                HorzAlign="Center", VertAlign="Center", TextAlign="Center", FontVector="Y", FontSize=3,
                FontWidth=-2, FontScale=1, LineSpacing=1.2, Group=-1, NetId=-1, Locked="N", Selected="N")
        points(s, [(x, y)])
        tl = sub(s, "TextLines")
        sub(tl, "TextLine", text)
    write(root, "beeper.dipxml")


