def component_library(parent, symbol_keys, pattern_keys, name="Beeper", standalone=False):
    attrs = dict(Type="DipTrace-ComponentLibrary", Name=name, Hint="Padauk beeper parts",
                 Version=VERSION, Units="mm")
    if standalone:
        attrs["UID32"] = "1587266401"
    lib = ET.Element("Library", attrs) if parent is None else sub(parent, "Library", **attrs)
    plib = sub(lib, "Library", Type="DipTrace-PatternLibrary", Name=name, Hint="Padauk beeper footprints",
               Version=PATTERN_VERSION, Units="mm")
    styles = sub(plib, "PadStyles")
    used = {key for pk in pattern_keys for _, key, _, _ in PATTERNS[pk].pads}
    for key, st in PAD_STYLES.items():
        if key in used:
            st.xml(styles)
    pats = sub(plib, "Patterns")
    for i, key in enumerate(pattern_keys):
        PATTERNS[key].xml(pats, i)
    comps = sub(lib, "Components")
    for i, key in enumerate(symbol_keys):
        SYMBOLS[key].xml(comps, i, pattern_keys)
    return lib


