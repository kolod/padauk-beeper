#!/usr/bin/env python3
"""Generate the DipTrace hardware project for the Padauk beeper.

Writes DipTrace XML files next to this script:

  beeper_library.elixml  component library (symbols + footprints), open in Component Editor
  beeper.dchxml          schematic (only with --schematic, see below)
  beeper.dipxml          placed PCB with nets, unrouted (only with --pcb, see below)

The schematic and the PCB have been arranged and routed by hand in DipTrace, so only the
library is regenerated by default. `--schematic` and `--pcb` overwrite those files with the
generated layout and lose the manual work.

Everything is in millimetres, Y axis up. Footprint dimensions come from the
manufacturer drawings as captured in the KiCad footprint library (see README.md).

Run:  python generate.py [--schematic] [--pcb]
"""

